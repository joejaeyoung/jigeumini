import { expect, test } from '@playwright/test';
const now = Date.parse('2026-10-25T12:00:00Z'), a = 'a'.repeat(32), b = 'b'.repeat(32);
const iso = (seconds = 0) => new Date(now + seconds * 1000).toISOString();
const uuid = (id: number) => `00000000-0000-4000-8000-${String(id).padStart(12, '0')}`;
const event = (id: number, channelId = a, seconds = -10) => ({ spikeId: uuid(id), channelId, evaluatedAt: iso(seconds), receivedAt: iso(), count: 100, baseline: 50, ratio: 2, algorithmVersion: 'chat-spike-v1', valid: true, qualityWarning: null, delayed: seconds < -600 });
test('관심 필터·읽음 유지·지연·품질 정정·페이지 이동과 작은 화면', async ({ page }) => {
  await page.clock.install({ time: now });
  await page.addInitScript(([first, second]) => { if (!localStorage.getItem('jigeumini.saved-channels.v1')) localStorage.setItem('jigeumini.saved-channels.v1', JSON.stringify([first, second])); }, [a, b]);
  await page.route('**/api/channels**', route => route.fulfill({ json: { asOf: iso(), scope: 'COLLECTED_CHANNELS_ONLY', channels: [a, b].map((id, i) => ({ channelId: id, channelName: `합성 방송 ${i + 1}`, title: '합성 제목', categoryId: 'game', categoryName: '게임', thumbnailUrl: null, liveStatus: 'LIVE', freshness: 'FRESH', reason: 'NONE', checkedAt: iso(), expiresAt: iso(60) })).filter(meta => new URL(route.request().url()).searchParams.get('ids')?.split(',').includes(meta.channelId)) } }));
  let revised = false;
  await page.route('**/api/v1/notifications?**', route => {
    const params = new URL(route.request().url()).searchParams;
    const events = params.get('cursor') ? [event(4, a, -900)] : [revised ? { ...event(1), valid: false, qualityWarning: 'COLLECTION_REVISED' } : event(1), event(2, b, -700), event(3, a, -30)];
    return route.fulfill({ json: { asOf: iso(), events: events.filter(e => params.get('channels')?.split(',').includes(e.channelId)), nextCursor: params.get('cursor') ? null : `${iso(-700)}|${uuid(2)}` } });
  });
  await page.goto('/notifications');
  await expect(page.locator('.notification-item')).toHaveCount(3);
  await expect(page.locator('.notification-item.is-new')).toHaveCount(2);
  await expect(page.getByText('늦게 도착한 기록')).toBeVisible();
  await page.getByRole('button', { name: '읽음으로 표시' }).first().click();
  await page.reload();
  await expect(page.locator('.notification-item.is-new')).toHaveCount(1);
  await expect(page.getByRole('button', { name: '읽음', exact: true })).toHaveCount(1);
  await page.getByRole('button', { name: '더 이전 알림' }).click();
  await expect(page.locator('.notification-item')).toHaveCount(1);
  await page.getByLabel('관심 채널 필터').selectOption(b);
  await expect(page.locator('.notification-item')).toHaveCount(1);
  await expect(page.getByRole('button', { name: '이전 페이지' })).toHaveCount(0);
  await expect(page.locator('.notification-item')).toContainText('합성 방송 2');
  await page.getByLabel('관심 채널 필터').selectOption('');revised = true;
  await page.clock.fastForward(5000);
  await expect(page.getByText('수집 불완전이 확인되어 급상승 판정을 보류했어요.')).toBeVisible();
  await page.setViewportSize({ width: 320, height: 740 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.route('**/api/v1/notifications?**', route => route.fulfill({ status: 503, body: '' }));
  await page.clock.fastForward(5000);
  await expect(page.getByRole('alert')).toContainText('갱신하지 못했어요');
  await expect(page.locator('.notification-item.is-new')).toHaveCount(0);
});
test('관심 방송이 없으면 안내하고 중복 응답은 성공으로 표시하지 않는다', async ({ page }) => {
  await page.route('**/api/channels**', route => route.fulfill({ status: 503, body: '' }));
  await page.route('**/api/v1/notifications?**', route => route.fulfill({ json: { asOf: iso(), events: [], nextCursor: null } }));
  await page.goto('/notifications');
  await expect(page.getByText('관심 방송을 먼저 저장해주세요')).toBeVisible();
  await page.evaluate(id => localStorage.setItem('jigeumini.saved-channels.v1', JSON.stringify([id])), a);
  await page.route('**/api/v1/notifications?**', route => route.fulfill({ json: { asOf: iso(), events: [event(1), event(1)], nextCursor: null } }));
  await page.reload();await expect(page.getByRole('alert')).toBeVisible();
  await expect(page.locator('.notification-item')).toHaveCount(0);
});
